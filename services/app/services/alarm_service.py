# -*- coding: utf-8 -*-
"""Классификация тревожных сообщений СМВУ (по ответам заказчика от 28.09.2026).

Формулировки заказчика:
  * запись журнала с `тревожное = t` диспетчеры называют **«тревожное сообщение»**;
    прежде чем отнести событие к инцидентам, профилактике (ППР) или ошибкам,
    диспетчер/дежурный инженер проводят дополнительную проверку (в сервисе это решение
    по прогнозу: подтвердить / отклонить / профилактика);
  * **авария** — угроза жизни человека; группы: пожар, наводнение, газ, террор,
    аномальная температура;
  * сработки охранной системы (люк, аварийный выход, дверь, движение, стекло) — тоже
    разновидность аварии, категория «террор, проникновение нарушителя»;
  * «потеря всей связи» / «потеря всего электроснабжения» — это **инциденты**, а не аварии,
    но косвенно допускают аварию из-за «слепоты систем».

Модуль не меняет ML-модель: он только называет класс последствия для UI/отчётов
(вес последствия остаётся в `research/inference_contract.SEVERITY_BY_TYPE`).
"""
from __future__ import annotations

# группа аварии -> типы датчиков (значения `тип_датчика` из справочника каналов)
ALARM_GROUPS: dict[str, tuple[str, ...]] = {
    "пожар": ("Датчик дыма", "Ручной извещатель", "Тепловой датчик"),
    "наводнение": ("Датчик затопления", "Состояние насоса"),
    "газ": ("Газовый датчик",),
    "террор": ("КД Люк", "9-секционный люк", "КД Дверь", "КД АВ", "Стекло", "Датчик движения"),
    "аномальная температура": ("Датчик температуры",),
}

# группа инцидента -> типы датчиков (не авария, но «слепые зоны» → косвенный риск аварии)
INCIDENT_GROUPS: dict[str, tuple[str, ...]] = {
    "электроснабжение": ("Состояние фазы",),
    "связь": (),          # потеря связи — свойство объекта (молчание всех каналов), не тип канала
}

# охранные каналы: по их сработкам строится маршрут движения нарушителя
SECURITY_TYPES: tuple[str, ...] = ALARM_GROUPS["террор"]

CLASS_ALARM, CLASS_INCIDENT = "авария", "инцидент"

_GROUP_BY_TYPE: dict[str, tuple[str, str, bool]] = {}
for _g, _types in ALARM_GROUPS.items():
    for _t in _types:
        _GROUP_BY_TYPE.setdefault(_t, (CLASS_ALARM, _g, False))
for _g, _types in INCIDENT_GROUPS.items():
    for _t in _types:
        _GROUP_BY_TYPE.setdefault(_t, (CLASS_INCIDENT, _g, True))


def alarm_class(channel_type: str | None) -> dict:
    """Класс события для типа канала.

    Возвращает {"класс": "авария"|"инцидент"|None, "группа": str|None,
    "косвенно_авария": bool} — «косвенно» означает инцидент, который может
    предшествовать аварии (слепые зоны: питание/связь).
    """
    got = _GROUP_BY_TYPE.get(str(channel_type))
    if not got:
        return {"класс": None, "группа": None, "косвенно_авария": False}
    cls, group, indirect = got
    return {"класс": cls, "группа": group, "косвенно_авария": indirect}


def is_security(channel_type: str | None) -> bool:
    """Охранный канал (люк/АВ/дверь/движение/стекло) — «террор, проникновение»."""
    return str(channel_type) in SECURITY_TYPES


def group_ru() -> dict:
    """Справочник групп для справки/UI/доков."""
    return {"авария": {g: list(t) for g, t in ALARM_GROUPS.items()},
            "инцидент": {g: list(t) for g, t in INCIDENT_GROUPS.items()}}
